@router.post("/delete", response_class=HTMLResponse)
def delete_short_videos(request: Request, selected: list[str] = Form(default=[])):
    """Deletes a video together with its companion files -- but ONLY for a video whose
    duration is actually under the configured NFO_SHORT_VIDEO_SECS threshold (default
    10s), re-checked here server-side with a fresh mediainfo read (never trusting the
    "is_short" flag the browser last saw, which could be stale if the file changed, or
    simply tampered with in a replayed request). This is a real, unrecoverable
    os.remove(), so every candidate is re-verified independently and anything that
    doesn't pass is skipped and reported rather than guessed at.

    folder.jpg is deliberately NOT deleted -- it's one shared file per folder (the
    directory's own cover image), not a per-video companion, so removing one short clip
    must never take the whole folder's artwork with it.
    """
    short_video_secs = settings.load_nfo_defaults().short_video_secs
    results = []
    for video in selected:
        try:
            pathsafety.check_allowed(video)
        except HTTPException as e:
            results.append({
                "path": video, "filename": os.path.basename(video),
                "status": "error", "message": str(e.detail),
            })
            continue
        results.append(nfocore.delete_short_video_with_companions(video, short_video_secs))

    return templates.TemplateResponse(request, "_delete_results.html", {"results": results})
