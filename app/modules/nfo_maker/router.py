"""
router.py — the NFO Maker web module (#6): generates Kodi .nfo files + poster/fanart/
thumb/folder.jpg images for home videos. Ported from HomeVideo_NFO_Maker_new.sh -- see
core/nfocore.py's module docstring for exactly what was and wasn't carried over (in
particular: GPS/location and AI-description data are READ-ONLY here, never fetched or
generated by this module itself).

Mounted under /nfo by app/main.py. Two-phase, like GPS Sidecar/AI Description/Collage:
/scan/start is the cheap phase (find candidate videos for the selected mode, read each
one's existing .xmp sidecar + mediainfo/exiftool metadata, check which already have an
.nfo and whether -O/--older protects it) and shows them as a selectable list; /generate/
start is the expensive phase (ffmpeg thumbnail extraction + the actual .nfo write) and
only runs for whichever videos are still selected.

Same lesson already applied to the Collage module's own force-checkbox bug: every
setting that affects /generate/start (force/force-jpg/force-timestamp/ai-description/
nolocation/older) is read LIVE off #browse-form at the moment "NFOs erstellen" is
clicked (hx-include="#browse-form" on the scan-form), not snapshotted back when
"Scannen" was clicked -- so toggling "Vorhandene .nfo überschreiben" after seeing which
videos already have one takes effect. Only `path`/`root_path`/`depth`/`mode` are fixed
at scan time, since changing any of those would invalidate the candidate list itself.
"""
