def _older_cutoff_epoch(older: int) -> float:
    """-O/--older: a calendar-date cutoff (today + older days), compared by DATE only
    (hours never considered) -- same as the CLI's OLDER_CUTOFF_EPOCH."""
    cutoff_date = date.today().fromordinal(date.today().toordinal() + older)
    return datetime(cutoff_date.year, cutoff_date.month, cutoff_date.day).timestamp()


def _protected_by_older(nfo_path: str, older: int | None) -> bool:
    if older is None or not os.path.exists(nfo_path):
        return False
    try:
        nfo_mtime = os.path.getmtime(nfo_path)
    except OSError:
        return False
    nfo_date = datetime.fromtimestamp(nfo_mtime).date()
    nfo_date_epoch = datetime(nfo_date.year, nfo_date.month, nfo_date.day).timestamp()
    return nfo_date_epoch > _older_cutoff_epoch(older)


def _candidate_videos(path: str, depth: int, mode: str) -> tuple[list[str], str]:
    """Returns (videos, info_message) for the selected mode."""
    if mode == "repair-ai":
        nfos = nfocore.scan_garbled_nfos(path, depth)
        videos = [v for v in (nfocore.nfo_video_sibling(n) for n in nfos) if v]
        return videos, f"{len(nfos)} .nfo-Datei(en) mit garbled AI-Beschreibung gefunden, {len(videos)} mit passendem Video."
    if mode == "repair-bad-ai":
        nfos = nfocore.scan_bad_ai_nfos(path, depth)
        videos = [v for v in (nfocore.nfo_video_sibling(n) for n in nfos) if v]
        return videos, f"{len(nfos)} .nfo-Datei(en) mit unbrauchbarer AI-Beschreibung gefunden, {len(videos)} mit passendem Video."
    if mode == "repair-italic":
        nfos = nfocore.scan_italic_nfos(path, depth)
        videos = [v for v in (nfocore.nfo_video_sibling(n) for n in nfos) if v]
        return videos, f"{len(nfos)} .nfo-Datei(en) mit altem [I]/[/I]-Format gefunden, {len(videos)} mit passendem Video."
    if mode in ("repair-missing-ai", "repair-missing"):
        if not settings.load_nfo_defaults().ai_description_enabled:
            return [], "AI-Beschreibungen sind nicht aktiviert – dieser Modus braucht sie (sonst würde jede .nfo grundlos passen)."
        if mode == "repair-missing-ai":
            nfos = nfocore.scan_missing_ai_nfos(path, depth)
            videos = [v for v in (nfocore.nfo_video_sibling(n) for n in nfos) if v]
            return videos, f"{len(nfos)} .nfo-Datei(en) ohne AI-Beschreibung gefunden, {len(videos)} mit passendem Video."
        nfos, n_ai, n_loc = nfocore.scan_missing_nfos(path, depth)
        videos = [v for v in (nfocore.nfo_video_sibling(n) for n in nfos) if v]
        return videos, (f"{len(nfos)} .nfo-Datei(en) zu erneuern ({n_ai} ohne AI-Beschreibung, {n_loc} ohne Ort obwohl das "
                        f".xmp jetzt GPS hat), {len(videos)} mit passendem Video.")
    all_videos = nfocore.find_videos(path, depth)
    if mode == "reintegrate-ai":
        videos = nfocore.scan_reintegrate_candidates(all_videos)
        return videos, f"{len(videos)} von {len(all_videos)} Video(s) haben bereits eine saubere AI-Beschreibung im .xmp-Sidecar."
    return all_videos, ""


def _build_row(video: str, older: int | None, skip_location: bool, ai_enabled: bool,
               geo_color: str, scanned_path: str, mode: str, short_video_secs: int) -> dict:
    base_dir = os.path.dirname(video)
    stem = os.path.splitext(os.path.basename(video))[0]
    nfo_path = os.path.join(base_dir, stem + ".nfo")
    existing_nfo = os.path.exists(nfo_path)
    protected = _protected_by_older(nfo_path, older)

    geo = nfocore.GeoSidecar()
    if not skip_location:
        geo = nfocore.read_geo_sidecar(video + ".xmp")

    meta = nfocore.extract_video_metadata(video)
    xmp_cam, _src = nfocore.camera_name_from_sidecar(video + ".xmp")
    if xmp_cam:
        meta.vsource = xmp_cam
    try:
        size_bytes = os.path.getsize(video)
    except OSError:
        size_bytes = 0

    video_root = settings.video_root()
    if video_root and video.startswith(video_root.rstrip("/") + "/"):
        sub_path = video[len(video_root.rstrip("/")) + 1:]
        sub_path = os.path.dirname(sub_path)
    else:
        sub_path = pathsafety.rel_subdir(scanned_path, video) or os.path.basename(base_dir)

    geo_summary = ""
    if geo.exists:
        parts = [p for p in (geo.country, geo.state, geo.city, geo.street) if p]
        geo_summary = ", ".join(parts) if parts else "No Location"

    # "Needs attention": the video's own .xmp sidecar is missing or incomplete -- no
    # location data at all, no AI description, or a garbled one -- regardless of
    # whether it already has an .nfo. This is the smart filter's selection criterion
    # (see _scan_list.html's "Nur unvollständige auswählen"): it flags videos worth
    # running GPS Sidecar / AI-Beschreibung on BEFORE (re)generating their .nfo here,
    # since this module only ever reads what's already in the sidecar.
    reasons = []
    if not geo.exists:
        reasons.append("kein .xmp-Sidecar")
    elif not (geo.country or geo.state or geo.city or geo.street):
        reasons.append("kein Ort im Sidecar")
    if ai_enabled:
        if not geo.ai_description:
            reasons.append("keine AI-Beschreibung im Sidecar")
        elif nfocore.ai_description_is_garbled(geo.ai_description):
            reasons.append("AI-Beschreibung im Sidecar ist garbled")

    # Default checkbox state: in normal mode, a video that already has an .nfo is a
    # deliberate overwrite -- default UNCHECKED so browsing "which videos already have
    # one" (via "Weiter scannen") doesn't default to regenerating all of them. In a
    # repair-*/reintegrate-ai mode every candidate was specifically selected because its
    # .nfo needs fixing, so it defaults CHECKED unless -O/--older protects it.
    would_skip = existing_nfo if mode == "normal" else protected

    return {
        "path": video, "filename": os.path.basename(video), "nfo_path": nfo_path,
        "existing_nfo": existing_nfo, "protected_by_older": protected,
        "would_skip": would_skip,
        "rel_dir": pathsafety.rel_subdir(scanned_path, video),
        "sub_path": sub_path,
        "geo_exists": geo.exists, "geo_summary": geo_summary,
        "ai_description": geo.ai_description if ai_enabled else "",
        "ai_garbled": bool(geo.ai_description) and nfocore.ai_description_is_garbled(geo.ai_description),
        "needs_attention": bool(reasons), "needs_attention_reasons": reasons,
        # "Short video" filter: a probably-accidental recording worth reviewing for
        # deletion. meta_error (mediainfo couldn't read the file) deliberately does NOT
        # count as short -- duration_secs is 0 in that case too, and a short-video DELETE
        # is destructive, so an unreadable file must never be silently caught by it.
        "duration_secs": meta.duration_secs,
        "is_short": not meta.error and 0 < meta.duration_secs < short_video_secs,
        "vsource": meta.vsource, "width": meta.width, "height": meta.height,
        "duration_display": nfocore.format_duration(meta.duration_secs),
        "size_display": nfocore.format_size(size_bytes),
        "meta_error": meta.error,
    }


def scan_start_work(job, depth, handoff_entry, include_existing, mode, offset, path, scan_id, limit=0):
    """Background work of scan_start (extracted so the Jahreslauf can call it without a request)."""
    defaults = settings.load_nfo_defaults()
    step = stepper.resume("nfo", scan_id, offset)
    resumed = step is not None
    if resumed:
        videos = step.paths
        info_message = step.meta.get("info_message", "")
        existing_count = step.meta.get("existing_count", 0)
    elif handoff_entry is not None:
        videos = [p for p in handoff_entry["file_paths"] if os.path.exists(p) and nfocore.is_nfo_video(p)]
        info_message = ""
    else:
        videos, info_message = _candidate_videos(path, depth, mode)
        if limit and limit > 0 and mode != "normal" and len(videos) > limit:
            # --limit of the script: repair runs in portions (the next run finds the rest, repaired ones no longer match)
            info_message = (info_message + " " if info_message else "") + f"Begrenzt auf die ersten {limit} von {len(videos)} Video(s) (Limit)."
            videos = videos[:limit]

    # Two-stage scan (mode == "normal" only -- repair-*/reintegrate-ai modes are
    # inherently about videos that already HAVE an .nfo, so include_existing has no
    # meaning there and every candidate is built as usual): cheaply split off videos
    # that already have an .nfo (a plain os.path.exists check) BEFORE running the
    # expensive _build_row()/extract_video_metadata() on them. Unless the user has
    # asked to "Weiter scannen" (include_existing), only the without-nfo videos are
    # actually built into rows; existing_count tells the template how many were
    # held back so it can offer that follow-up scan.
    if not resumed:
        existing_count = 0
    if not resumed and mode == "normal" and not include_existing:
        without_nfo = []
        for video in videos:
            base_dir = os.path.dirname(video)
            stem = os.path.splitext(os.path.basename(video))[0]
            nfo_path = os.path.join(base_dir, stem + ".nfo")
            if os.path.exists(nfo_path):
                existing_count += 1
            else:
                without_nfo.append(video)
        videos = without_nfo

    if not resumed:
        step = stepper.start("nfo", videos, {"info_message": info_message, "existing_count": existing_count},
                             unlimited=handoff_entry is not None)
        videos = step.paths
    job.total = len(videos)

    rows = []
    for i, video in enumerate(videos):
        if job.cancel_event.is_set():
            break
        job.done, job.current_name = i, os.path.basename(video)
        rows.append(_build_row(
            video, defaults.older, defaults.skip_location, defaults.ai_description_enabled,
            defaults.geo_color, path, mode, defaults.short_video_secs,
        ))
    else:
        job.done = len(videos)

    return {
        "rows": rows, "error": None, "info_message": info_message,
        "all_rows_json": json.dumps(rows), "scanned_path": path, "mode": mode,
        "existing_count": existing_count, "include_existing": include_existing,
        "short_video_secs": defaults.short_video_secs,
        "step": step.to_dict(), "step_url": "/nfo/scan/start",
    }


@router.post("/scan/start", response_class=HTMLResponse)
def scan_start(
    request: Request,
    path: str = Form(...),
    root_path: str = Form(""),
    depth: int = Form(1),
    mode: str = Form("normal"),
    limit: int = Form(0),
    include_existing: bool = Form(False),
    handoff_id: str = Form(""),
    scan_id: str = Form(""),
    offset: int = Form(0),
):
    pathsafety.check_allowed(path)
    pathsafety.check_within_root(path, root_path)
    if mode not in MODES:
        mode = "normal"
    depth = max(0, min(7, depth))

    if not os.path.exists(path):
        return templates.TemplateResponse(request, "_scan_list.html", {
            "error": f"Pfad nicht gefunden: {path}", "rows": [],
        })

    # A handoff_id (from "Weiter zu NFO Maker") carries the EXACT video files
    # AI-Beschreibung just touched -- use those directly instead of walking the whole
    # folder, same rationale as the other hops (see core/handoff.py). Falls back to the
    # normal mode-based candidate search when there's no handoff_id, or it's
    # expired/invalid.
    handoff_entry = handoff.fetch(handoff_id)

    job = jobs.create_job()
    job.phase = "Videos suchen"


    jobs.run_job(job, lambda: scan_start_work(job, depth=depth, handoff_entry=handoff_entry, include_existing=include_existing, mode=mode, offset=offset, path=path, scan_id=scan_id, limit=max(0, limit)))
    return templates.TemplateResponse(request, "_progress.html", {
        "job_id": job.id, "job": job.to_progress_dict(),
        "poll_url": f"/nfo/scan/progress/{job.id}", "cancel_url": f"/nfo/scan/cancel/{job.id}",
    })


@router.get("/scan/progress/{job_id}", response_class=HTMLResponse)
def scan_progress(request: Request, job_id: str):
    job = jobs.get_job(job_id)
    if job is None:
        return templates.TemplateResponse(request, "_scan_list.html", {
            "error": "Vorgang nicht gefunden (abgelaufen oder Server neu gestartet) — bitte erneut laden.",
            "rows": [],
        })
    if job.status == "running":
        return templates.TemplateResponse(request, "_progress.html", {
            "job_id": job.id, "job": job.to_progress_dict(),
            "poll_url": f"/nfo/scan/progress/{job.id}", "cancel_url": f"/nfo/scan/cancel/{job.id}",
        })
    if job.status == "cancelled":
        # The scan loop checks cancel_event once per video and breaks immediately (see
        # work() above) -- whatever it had already built before that point is still a
        # perfectly usable result (same shape as a completed scan's), so "Fertig" during
        # a big depth-7 walk hands back the videos found so far instead of throwing them
        # away. Only a genuinely empty result (cancelled before any row was built) falls
        # back to the plain "cancelled" message.
        result = job.result or {}
        if result.get("rows"):
            ctx = dict(result)
            n = len(result["rows"])
            stop_note = f"Suche gestoppt -- {n} bisher gefundene(s) Video(s) werden unten angezeigt."
            ctx["info_message"] = (stop_note + " " + ctx["info_message"]) if ctx.get("info_message") else stop_note
            return templates.TemplateResponse(request, "_scan_list.html", ctx)
        return templates.TemplateResponse(request, "_scan_list.html", {
            "error": None, "rows": [], "cancelled_info": "Suche abgebrochen.",
        })
    if job.status == "error":
        return templates.TemplateResponse(request, "_scan_list.html", {
            "error": f"Fehler bei der Video-Suche: {job.error}", "rows": [],
        })
    return templates.TemplateResponse(request, "_scan_list.html", job.result or {})


@router.post("/scan/cancel/{job_id}")
def scan_cancel(job_id: str):
    jobs.cancel_job(job_id)
    return HTMLResponse(status_code=204, content="")


def _parse_older(raw: str) -> int | None:
    raw = (raw or "").strip()
    if not raw:
        return None
    try:
        v = int(raw)
    except ValueError:
        return None
    return min(0, v)


def _write_one(video: str, row: dict, *, force_nfo: bool, force_jpg: bool, force_timestamp: bool,
               ai_enabled: bool, skip_location: bool, older: int | None, geo_color: str,
               defaults: settings.NfoDefaults) -> dict:
    base_dir = os.path.dirname(video)
    stem = os.path.splitext(os.path.basename(video))[0]
    nfo_path = os.path.join(base_dir, stem + ".nfo")
    touched: list[str] = []

    # Hash-based, not built from raw filename characters -- see the Collage module's
    # own "& in a trip name breaks hx-target" bug fix for why (an unescaped '&' or other
    # special character in a CSS id selector makes htmx's querySelector() throw,
    # silently breaking the "Neu erzeugen" button).
    row_id = "nfo-row-" + hashlib.md5(video.encode("utf-8")).hexdigest()
    result = {
        "path": video, "filename": os.path.basename(video), "nfo_path": nfo_path, "row_id": row_id,
        "nfo_written": False, "skipped": False, "skip_reason": "", "error": "",
        "thumb_written": False, "vsource": "", "geo_summary": "", "ai_used": False,
    }

    if not os.path.exists(video):
        result["error"] = "Video nicht mehr gefunden -- Vorschau neu laden."
        return result

    pathsafety.check_allowed(video)

    folder_jpg = os.path.join(base_dir, "folder.jpg")
    poster_jpg = os.path.join(base_dir, stem + "-poster.jpg")
    fanart_jpg = os.path.join(base_dir, stem + "-fanart.jpg")
    thumb_jpg = os.path.join(base_dir, stem + "-thumb.jpg")

    thumb_seek, folder_seek = nfocore.compute_seek_times(stem, video)
    if nfocore.generate_folder_jpg(video, folder_jpg, folder_seek, force_jpg):
        pass  # folder.jpg isn't a per-video "touched" file for mtime-restore purposes
    if nfocore.generate_poster_fanart_thumb(video, poster_jpg, fanart_jpg, thumb_jpg, thumb_seek, force_jpg):
        touched += [poster_jpg, fanart_jpg, thumb_jpg]
        result["thumb_written"] = True
    elif force_timestamp:
        touched += [poster_jpg, fanart_jpg, thumb_jpg]

    existing_nfo = os.path.exists(nfo_path)
    protected = _protected_by_older(nfo_path, older)
    if existing_nfo and (not force_nfo or protected):
        result["skipped"] = True
        result["skip_reason"] = (
            f"durch -O/--older geschützt (zuletzt geändert innerhalb des Schutzfensters)"
            if protected else "existiert bereits"
        )
        if force_timestamp:
            touched.append(nfo_path)
        if touched:
            mtimecore.restore_many(touched)
        return result

    geo = nfocore.GeoSidecar()
    if not skip_location:
        geo = nfocore.read_geo_sidecar(video + ".xmp")
    geo_line = build_geo_line = nfocore.build_geo_plot_line(geo, geo_color)
    ai_line, ai_note = ("", "")
    if ai_enabled:
        ai_line, ai_note = nfocore.build_ai_plot_line(geo)
        result["ai_used"] = bool(ai_line)

    meta = nfocore.extract_video_metadata(video)
    # camera: the readable name GPS Sidecar stored in the .xmp (XMP-mon:CameraName) wins; only without it
    # the detection above (which also applies camera_names.json) is used
    mon = nfocore.read_mon_fields(video + ".xmp")
    xmp_cam, _xmp_src = nfocore.camera_name_from_sidecar(video + ".xmp")
    if xmp_cam:
        meta.vsource = xmp_cam
    context_line = nfocore.build_context_plot_line(mon)
    try:
        mtime_epoch = os.path.getmtime(video)
        size_bytes = os.path.getsize(video)
    except OSError:
        mtime_epoch, size_bytes = 0, 0
    file_date = datetime.fromtimestamp(mtime_epoch) if mtime_epoch else datetime.now()
    date_used = file_date.strftime("%Y-%m-%d")

    video_root = settings.video_root()
    if video_root and video.startswith(video_root.rstrip("/") + "/"):
        sub_path = os.path.dirname(video[len(video_root.rstrip("/")) + 1:])
    else:
        sub_path = os.path.basename(base_dir)

    filename = os.path.basename(video)
    title = f"{filename} ({nfocore.format_duration(meta.duration_secs)})"
    xml = nfocore.build_nfo_xml(
        title=title, sort_title=title, year=file_date.strftime("%Y"), premiered=date_used,
        duration_secs=meta.duration_secs, width=meta.width, height=meta.height, aspect=meta.aspect,
        codec=meta.codec, format_id=meta.format_id, bitrate_mbps=meta.bitrate_mbps,
        container=meta.container, framerate=meta.framerate, bitdepth=meta.bitdepth,
        aformat=meta.aformat, achannels=meta.achannels, vsource=meta.vsource,
        video_size_display=nfocore.format_size(size_bytes), sub_path=sub_path,
        geo_line=geo_line, ai_line=ai_line, stem=stem, created_date=date_used, defaults=defaults,
        context_line=context_line,
    )
    try:
        with open(nfo_path, "w", encoding="utf-8") as fh:
            fh.write(xml)
        result["nfo_written"] = True
        touched.append(nfo_path)
    except OSError as e:
        result["error"] = f".nfo konnte nicht geschrieben werden: {e}"

    result["vsource"] = meta.vsource
    geo_parts = [p for p in (geo.country, geo.state, geo.city, geo.street) if p]
    result["geo_summary"] = ", ".join(geo_parts) if geo_parts else ("No Location" if geo.exists else "")
    if ai_note and not result["ai_used"]:
        result["ai_note"] = ai_note

    if touched:
        mtimecore.restore_many(touched)
    return result


def generate_start_work(job, ai_description_enabled, defaults, force, force_jpg, force_timestamp, mode, older_val, skip_location, to_process):
    """Background work of generate_start (extracted so the Jahreslauf can call it without a request)."""
    results = []
    for i, row in enumerate(to_process):
        if job.cancel_event.is_set():
            break
        job.done, job.current_name = i, row.get("filename", "")
        result = _write_one(
            row["path"], row, force_nfo=(force or mode != "normal"), force_jpg=force_jpg, force_timestamp=force_timestamp,
            ai_enabled=ai_description_enabled, skip_location=skip_location, older=older_val,
            geo_color=defaults.geo_color, defaults=defaults,
        )
        results.append(result)
    else:
        job.done = len(to_process)

    return {
        "results": results,
        "cancelled_info": (
            f"Abgebrochen nach {job.done} von {job.total} Video(s)." if job.cancel_event.is_set() else None
        ),
    }


@router.post("/generate/start", response_class=HTMLResponse)
def generate_start(
    request: Request,
    selected: list[str] = Form(default=[]),
    all_rows: str = Form(...),
    force: bool = Form(False),
    force_jpg: bool = Form(False),
    force_timestamp: bool = Form(False),
    ai_description_enabled: bool = Form(False),
    skip_location: bool = Form(False),
    older: str = Form(""),
    mode: str = Form("normal"),
):
    """Reads force/force_jpg/force_timestamp/ai_description_enabled/skip_location/older
    LIVE off #browse-form at the moment "NFOs erstellen" is clicked -- see module
    docstring for why (same fix as the Collage module's own stale-settings bug)."""
    try:
        rows_data = json.loads(all_rows)
    except json.JSONDecodeError:
        raise HTTPException(status_code=400, detail="Ungültige Vorschau-Daten, bitte neu laden.")

    selected_set = set(selected)
    to_process = [r for r in rows_data if r["path"] in selected_set]
    older_val = _parse_older(older)
    defaults = settings.load_nfo_defaults()

    job = jobs.create_job()
    job.total = len(to_process)
    job.phase = "NFOs erstellen"


    jobs.run_job(job, lambda: generate_start_work(job, ai_description_enabled=ai_description_enabled, defaults=defaults, force=force, force_jpg=force_jpg, force_timestamp=force_timestamp, mode=mode, older_val=older_val, skip_location=skip_location, to_process=to_process))
    return templates.TemplateResponse(request, "_progress.html", {
        "job_id": job.id, "job": job.to_progress_dict(),
        "poll_url": f"/nfo/generate/progress/{job.id}", "cancel_url": f"/nfo/generate/cancel/{job.id}",
    })


@router.get("/generate/progress/{job_id}", response_class=HTMLResponse)
def generate_progress(request: Request, job_id: str):
    job = jobs.get_job(job_id)
    if job is None:
        return templates.TemplateResponse(request, "_results.html", {
            "error": "Vorgang nicht gefunden (abgelaufen oder Server neu gestartet) — bitte erneut laden.",
            "results": [],
        })
    if job.status == "running":
        return templates.TemplateResponse(request, "_progress.html", {
            "job_id": job.id, "job": job.to_progress_dict(),
            "poll_url": f"/nfo/generate/progress/{job.id}", "cancel_url": f"/nfo/generate/cancel/{job.id}",
        })
    if job.status == "error":
        return templates.TemplateResponse(request, "_results.html", {
            "error": f"Fehler beim Erstellen: {job.error}", "results": [],
        })
    return templates.TemplateResponse(request, "_results.html", job.result or {})


