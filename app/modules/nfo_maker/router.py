@router.get("/", response_class=HTMLResponse)
def index(request: Request, path: str = "", root_path: str = "", handoff_id: str = ""):
    root_folders = [rf.to_dict() for rf in settings.load_root_folders()]
    defaults = settings.load_nfo_defaults()
    # A handoff_id (from "Weiter zu NFO Maker") takes priority over plain path/root_path
    # -- it carries the EXACT video files AI-Beschreibung just touched (see
    # core/handoff.py). Resolving it here only sets path/root_path for prefill;
    # scan_start() re-resolves the same id for the actual video list once the form
    # submits.
    entry = handoff.fetch(handoff_id)
    if entry is not None:
        path, root_path = entry["path"], entry["root_path"]
    else:
        handoff_id = ""  # expired/invalid -- don't carry a dead id into the hidden field
    return templates.TemplateResponse(request, "index.html", {
        "media_root": pathsafety.MEDIA_ROOT,
        "root_folders": root_folders,
        "defaults": defaults,
        # Set only when arriving via the "Weiter zu NFO Maker" handoff from the
        # AI-Beschreibung module -- prefills Pfad for this one load and auto-submits
        # the scan (see index.html's initLastPath()), same pattern as the GPS
        # Sidecar/AI-Beschreibung handoffs.
        "prefill_path": path,
        "prefill_root_path": root_path,
        "prefill_handoff_id": handoff_id,
    })


